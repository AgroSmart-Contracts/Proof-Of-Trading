/**
 * SEP-1 stellar.toml for the issuer of the share assets: network, issuer account, organization,
 * and one [[CURRENCIES]] entry per share asset with its SAC (`contract`) and the proof hash it is
 * linked to. Values are TOML basic strings, escaped here.
 */
export type TomlShare = {
  shipment_ref: string;
  code: string;
  issuer: string;
  sac_id: string;
  proof_hash: string;
  face_value_usd?: number;
  commodity?: string;
  destination_region?: string;
};

export type TomlOrg = {
  name: string;
  url: string;
  description: string;
  email?: string;
  github?: string;
};

const q = (s: string) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n")}"`;

export function renderStellarToml(input: {
  networkPassphrase: string;
  issuer: string;
  org: TomlOrg;
  shares: TomlShare[];
  status?: "live" | "dead" | "test" | "private";
}): string {
  const issuers = new Set(input.shares.map((s) => s.issuer));
  if (issuers.size > 1 || (issuers.size === 1 && !issuers.has(input.issuer))) {
    throw new Error("every share asset must be issued by the stellar.toml issuer");
  }
  const lines = [
    "# Generated by scripts/stellar-toml.ts. Do not edit by hand.",
    'VERSION = "2.7.0"',
    `NETWORK_PASSPHRASE = ${q(input.networkPassphrase)}`,
    `ACCOUNTS = [${q(input.issuer)}]`,
    "",
    "[DOCUMENTATION]",
    `ORG_NAME = ${q(input.org.name)}`,
    `ORG_URL = ${q(input.org.url)}`,
    `ORG_DESCRIPTION = ${q(input.org.description)}`,
    ...(input.org.email ? [`ORG_OFFICIAL_EMAIL = ${q(input.org.email)}`] : []),
    ...(input.org.github ? [`ORG_GITHUB = ${q(input.org.github)}`] : []),
  ];
  for (const s of input.shares) {
    const what = [s.commodity, s.destination_region && `to ${s.destination_region}`].filter(Boolean).join(" ");
    lines.push(
      "",
      "[[CURRENCIES]]",
      `code = ${q(s.code)}`,
      `issuer = ${q(s.issuer)}`,
      `contract = ${q(s.sac_id)}`,
      `status = ${q(input.status ?? "test")}`,
      "display_decimals = 7",
      `name = ${q(`SPV share, shipment ${s.shipment_ref}`)}`,
      `desc = ${q(
        `Ordinary share in the SPV that holds the receivable and insurance of shipment ${s.shipment_ref}` +
          `${what ? ` (${what})` : ""}. One token is one share of 1.00 USD face value. ` +
          `Linked proof hash ${s.proof_hash}.`,
      )}`,
      `conditions = ${q(
        "Held only by investors approved by the issuer (AUTH_REQUIRED). The issuer may freeze (AUTH_REVOCABLE) or " +
          "claw back (AUTH_CLAWBACK_ENABLED) shares under its published policy. Holders are paid, pro rata, from what " +
          "the SPV collects, up to the fixed amount set in the offering terms. Not a loan.",
      )}`,
      "is_asset_anchored = false",
      ...(s.face_value_usd ? [`max_number = ${Math.round(s.face_value_usd)}`] : []),
      "is_unlimited = false",
    );
  }
  return lines.join("\n") + "\n";
}
